import {readFileSync, writeFileSync} from "node:fs";

const sourcePath = new URL("../src/core/unicode/confusables.txt", import.meta.url);
const outputPath = new URL("../src/core/unicode/confusables-data.json", import.meta.url);
const source = readFileSync(sourcePath, "utf8");
const unicodeVersion = source.match(/^# Version: (\d+\.\d+\.\d+)$/mu)?.[1];
const date = source.match(/^# Date: (\d{4}-\d{2}-\d{2})/mu)?.[1];
if (unicodeVersion === undefined || date === undefined) {
  throw new Error("The vendored Unicode confusables file is missing its version header.");
}

const map = {};
for (const line of source.split("\n")) {
  const entry = /^([0-9A-F]+)\s*;\s*([0-9A-F ]+?)\s*;\s*MA\s*#\*?\s*\(.*?\)\s*(.*?)\s*→/u.exec(line);
  if (entry === null) continue;
  const sourceCodepoint = Number.parseInt(entry[1] ?? "", 16).toString();
  const target = (entry[2] ?? "").trim().split(/\s+/u)
    .map((codepoint) => String.fromCodePoint(Number.parseInt(codepoint, 16))).join("");
  map[sourceCodepoint] = [target, entry[3] ?? ""];
}

if (Object.keys(map).length !== 6_565) {
  throw new Error(`Expected 6565 single-codepoint mappings, found ${Object.keys(map).length}.`);
}

const data = {
  _comment: "GENERATED by build-confusables-data.mjs from the pinned confusables.txt (Unicode UTS #39 confusables table). Do not edit by hand; re-run the build. See VENDOR.md for provenance and license.",
  unicodeVersion,
  date,
  map,
};
writeFileSync(outputPath, `${JSON.stringify(data)}\n`);
